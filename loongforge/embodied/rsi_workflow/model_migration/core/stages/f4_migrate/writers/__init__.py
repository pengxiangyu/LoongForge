"""The four write actions, and the rules they share.

Dispatch is by `action` and nothing else, so what happened to a slot can be read off the mapping
table instead of reconstructed from the diff. Each writer does one thing and is not allowed to
drift into another's job: `copy` does not rename, `adapt` does not change the maths, `wrap` does
not re-implement, `reimplement` must say why it had to.

Two rules hold for all four:

  provenance  every written file carries the segment, the slot, the action and the source location
              in its header. A migrated file whose origin cannot be read is not reviewable.
  no clobber  an F3 skeleton is replaced -- that is what it is for -- but already migrated content
              is not. For the shared files of the target framework (`model/registry.py`,
              `optimizer/optimizer.py`, ...) the writer leaves a `.f4-proposal` next to the target
              and reports `needs_merge`: those files already carry the other embodied models, and
              merging into them is a reviewed edit, not an automatic one.
"""
from pathlib import Path

PROPOSAL_SUFFIX = '.f4-proposal'
SKELETON_MARKER = '# Generated by F3'


def provenance(entry, source):
    """Header comment recording where a migrated file came from and under which action."""
    repo = source.get('repo', '<source repo>')
    commit = source.get('commit')
    origin = f'{repo}@{commit}' if commit else repo
    return (f'# Migrated by F4 ({entry["action"]}) for segment {entry["seg"]}, '
            f'slot {entry["slot"]}.\n'
            f'# Source: {origin} :: {entry["src"]}\n'
            f'# Reason: {entry["reason"]}\n')


def place(entry, target_root, text, shared, force=False):
    """Write `text` to the entry's target, or leave a proposal beside an existing file."""
    path = Path(target_root) / entry['dst']
    path.parent.mkdir(parents=True, exist_ok=True)
    record = {'seg': entry['seg'], 'slot': entry['slot'], 'action': entry['action'],
              'src': entry['src'], 'dst': entry['dst']}
    if path.exists() and not force:
        if entry['dst'] in shared:
            proposal = path.with_name(path.name + PROPOSAL_SUFFIX)
            proposal.write_text(text, encoding='utf-8')
            record.update(status='needs_merge', proposal=str(proposal),
                          note='shared target: merge by review, do not overwrite')
            return record
        if not path.read_text(encoding='utf-8').startswith(SKELETON_MARKER):
            record.update(status='kept',
                          note='already migrated; rerun with --force to replace')
            return record
    path.write_text(text, encoding='utf-8')
    record.update(status='written')
    return record
    path.write_text(text, encoding='utf-8')
    record.update(status='written')
    return record


def dispatch(entry, src_root, target_root, source, shared=(), force=False):
    """Route one mapping entry to its writer. Returns the write record."""
    from . import adapt, copy, reimplement, wrap
    writers = {'copy': copy.write, 'adapt': adapt.write, 'wrap': wrap.write,
               'reimplement': reimplement.write}
    writer = writers.get(entry['action'])
    if writer is None:
        return {'seg': entry['seg'], 'slot': entry['slot'], 'action': entry['action'],
                'dst': entry['dst'], 'status': 'error',
                'note': f'no writer for action {entry["action"]!r}'}
    return writer(entry, src_root, target_root, source, shared=shared, force=force)
