"""Builds the per-slot mapping table out of the anatomy, and checks one before it is written from.

The mapping says, for every slot: where the original implementation lives, where it lands, and
which of the four actions moves it. It adds nothing the anatomy does not already state -- src,
dst and action come from the structure source of truth -- so it cannot quietly relocate a slot;
what it adds is the check that the whole table holds together before any file is written:

  * the action is one of the four, and the entry names one segment and one slot
  * dst is declared in TREE_SPEC.slot_targets and matches the anatomy verbatim
  * a dst among the shared targets of the target framework uses `wrap` or `adapt`. Those files
    carry every other embodied model, so a migration reuses them; `copy` or `reimplement` there
    would overwrite working models with a port of one.
"""
import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[4]))

from core.stages.f3_scaffold.scaffold import TREE_SPEC, load_yaml, resolve_target   # noqa: E402
from validate.structure_judge import slots_of                                       # noqa: E402

ACTIONS = ('copy', 'adapt', 'wrap', 'reimplement')
REUSE_ACTIONS = ('wrap', 'adapt')
SCHEMA = Path(__file__).resolve().parent / 'MAPPING_SCHEMA.yaml'
DEFAULT_OUT = Path(__file__).resolve().parents[1] / 'mapping.yaml'


def build(anatomy, spec):
    """One entry per slot, in anatomy order. Returns (entries, problems)."""
    entries, problems = [], []
    for seg_id, slot in slots_of(anatomy):
        entry = {'seg': seg_id, 'slot': slot['slot'], 'src': slot.get('src'),
                 'dst': slot.get('dst'), 'action': slot.get('action'),
                 'reason': slot.get('reason') or f'declared by STEP_ANATOMY.yaml for {seg_id}'}
        if slot.get('name'):
            entry['name'] = slot['name']
        for field in ('reuse', 'rewrites'):                # what `wrap` and `adapt` need
            if slot.get(field):
                entry[field] = slot[field]
        for field in ('src', 'dst', 'action'):
            if not entry[field]:
                problems.append(f'{seg_id}.{slot["slot"]}: anatomy slot has no {field}')
        entries.append(entry)
    return entries, problems + check(entries, anatomy, spec)


def check(entries, anatomy, spec):
    """Every rule of MAPPING_SCHEMA.yaml, as a list of problems."""
    problems, seen = [], set()
    declared = {s['dst']: f'{seg}.{s["slot"]}' for seg, s in slots_of(anatomy) if s.get('dst')}
    shared = set(spec.get('shared_targets') or [])
    for entry in entries:
        where = f'{entry.get("seg")}.{entry.get("slot")}'
        key = (entry.get('seg'), entry.get('slot'), entry.get('name'))
        if key in seen:
            problems.append(f'{where}: two entries claim the same slot instance')
        seen.add(key)
        if entry.get('action') not in ACTIONS:
            problems.append(f'{where}: action {entry.get("action")!r} is not one of {ACTIONS}')
        if not entry.get('reason'):
            problems.append(f'{where}: no reason for the action')
        expected = resolve_target(spec, entry.get('slot'), anatomy['model_tag'], entry.get('name'))
        if expected is None:
            problems.append(f'{where}: slot is not declared in TREE_SPEC.slot_targets')
        elif entry.get('dst') != expected:
            problems.append(f'{where}: dst {entry.get("dst")!r} is not the TREE_SPEC target '
                            f'{expected!r}')
        if declared.get(entry.get('dst'), where) != where:
            problems.append(f'{where}: dst is owned by {declared[entry["dst"]]} in the anatomy')
        if entry.get('dst') in shared and entry.get('action') not in REUSE_ACTIONS:
            problems.append(f'{where}: {entry["dst"]} is shared by the target framework, so the '
                            f'action must be one of {REUSE_ACTIONS}, not {entry.get("action")!r}')
    return problems


def dump(entries, anatomy, path):
    import yaml
    header = ('# F4 mapping table, generated by map/build_mapping.py from STEP_ANATOMY.yaml.\n'
              '# Per-slot source to target; see map/MAPPING_SCHEMA.yaml for the rules.\n')
    body = yaml.safe_dump({'version': 4, 'model_tag': anatomy['model_tag'],
                           'source': anatomy.get('source', {}), 'entries': entries},
                          sort_keys=False, allow_unicode=True, width=100)
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(header + body, encoding='utf-8')


def main(argv=None):
    p = argparse.ArgumentParser(prog='build_mapping.py', description=__doc__)
    p.add_argument('action', choices=('build', 'check'))
    p.add_argument('--anatomy', required=True, help='STEP_ANATOMY.yaml from F2')
    p.add_argument('--tree-spec', default=str(TREE_SPEC))
    p.add_argument('--mapping', default=str(DEFAULT_OUT),
                   help='written by `build`, read by `check`')
    p.add_argument('--report')
    a = p.parse_args(argv)
    anatomy, spec = load_yaml(a.anatomy), load_yaml(a.tree_spec)
    if a.action == 'build':
        entries, problems = build(anatomy, spec)
        if not problems:
            dump(entries, anatomy, a.mapping)
    else:
        mapping = load_yaml(a.mapping)
        entries = mapping.get('entries') or []
        problems = check(entries, anatomy, spec)
    report = {'verdict': 'PASS' if not problems else 'FAIL', 'entries': len(entries),
              'mapping': str(a.mapping), 'problems': problems}
    text = json.dumps(report, indent=1, ensure_ascii=False) + '\n'
    if a.report:
        Path(a.report).parent.mkdir(parents=True, exist_ok=True)
        Path(a.report).write_text(text, encoding='utf-8')
    print(text, end='')
    return 0 if report['verdict'] == 'PASS' else 2


if __name__ == '__main__':
    raise SystemExit(main())
